/**
 * Academy checkpoint / fault library — one distinct definition set per shot type.
 *
 * This is the knowledge core of the Academy feature. Each shot type defines:
 *   - phases:   the key positions the video is segmented into
 *   - metrics:  measurable 2D pose quantities with benchmark ranges
 *   - faults:   detectable deviations, each with plain-language coaching copy,
 *               a drill, and search keywords used to match creator videos
 *
 * Every metric here is honestly computable from 17-keypoint 2D pose data
 * (MoveNet/COCO). Where a true 3D quantity (e.g. shoulder turn) is
 * approximated, the metric is a documented 2D proxy — e.g. apparent
 * shoulder-line compression on a face-on view.
 *
 * Metric values are produced by metrics.js; fault predicates below are
 * evaluated by analyze.js against those values.
 *
 * angle: which camera angle a metric/fault needs — 'face_on', 'down_the_line',
 * or 'any'. Metrics whose angle doesn't match the upload are skipped, never
 * guessed.
 */

