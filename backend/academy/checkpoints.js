const SHOT_TYPES = {
  driving: DRIVING,
  iron: IRON,
  bunker: BUNKER,
  chipping: CHIPPING,
  putting: PUTTING,
};

function getShotType(id) {
  const def = SHOT_TYPES[id];
  if (!def) throw new Error(`Unknown shot type: ${id}`);
  return def;
}

/** Metric ids tracked on the dashboard trend charts for a shot type. */
function progressMetricIds(shotTypeId) {
  return getShotType(shotTypeId)
    .metrics.filter((m) => m.progressMetric)
    .map((m) => m.id);
}

